/**
 * 会社名の表記ゆれを吸収する。
 * 「株式会社明治」「(株)明治」「明治」を同じものとして扱いたい。
 * 長音（ー）は残す。消すと別語と衝突しうるため。
 */
function normalizeCorp(name: string): string {
  return (name || "")
    .normalize("NFKC")
    .replace(/(株式会社|有限会社|合同会社|合資会社|一般社団法人|公益社団法人)/g, "")
    .replace(/[（(](?:株|有|同)[）)]/g, "")
    .replace(/[\s　]/g, "")
    .replace(/[-‐‑‒–—―・･.,、。'"`]/g, "")
    .toLowerCase();
}

/** 自動投稿を許す配信元か */
export function isAutoPostPublisher(corp: string): boolean {
  const c = normalizeCorp(corp);
  if (!c) return false;
  return AUTO_POST_PUBLISHERS.some((p) => c.includes(normalizeCorp(p)));
}
